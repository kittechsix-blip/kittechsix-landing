// Generates src/data/previews.ts from assets/previews/<appId>/captions.json.
// Each captions.json is [{ "file": "01-name.jpg", "caption": "..." }] in display order.
// Run by `bun run build`; re-run after adding or replacing screenshots.
import { readdirSync, readFileSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = 'assets/previews';
const out = {};
for (const id of existsSync(root) ? readdirSync(root).sort() : []) {
  const dir = join(root, id);
  if (!statSync(dir).isDirectory()) continue;
  const capFile = join(dir, 'captions.json');
  if (!existsSync(capFile)) throw new Error(`missing ${capFile}`);
  const caps = JSON.parse(readFileSync(capFile, 'utf8'));
  out[id] = caps.map(({ file, caption }) => {
    if (!existsSync(join(dir, file))) throw new Error(`${id}: ${file} listed in captions.json but missing`);
    if (!caption || caption.length > 80) throw new Error(`${id}: ${file} caption missing or too long`);
    return { src: `${root}/${id}/${file}`, caption };
  });
}
const body = `// GENERATED by scripts/build-previews.mjs from assets/previews/*/captions.json. Do not edit.
export interface PreviewShot { src: string; caption: string }
export const PREVIEWS: Record<string, PreviewShot[]> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/data/previews.ts', body);
console.log(`previews: ${Object.keys(out).length} apps, ${Object.values(out).flat().length} screens`);
